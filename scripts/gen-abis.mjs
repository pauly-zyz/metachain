#!/usr/bin/env node
// Generates packages/sdk/src/abis.ts from Foundry artifacts (run `forge build` in contracts/ first).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const contracts = [
  ["MetaTokenPaymaster", "metaTokenPaymasterAbi"],
  ["MetaPriceOracle", "metaPriceOracleAbi"],
  ["AgentPayments", "agentPaymentsAbi"],
  ["MockMETA", "mockMetaAbi"],
  ["MockAggregator", "mockAggregatorAbi"],
  ["MockUniswapV3Pool", "mockUniswapV3PoolAbi"],
];
let src = "// AUTO-GENERATED by scripts/gen-abis.mjs from contracts/out — do not edit.\n\n";
for (const [name, exportName] of contracts) {
  const artifact = JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8"));
  src += `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(root, "packages", "sdk", "src", "abis.ts"), src);
console.log("wrote packages/sdk/src/abis.ts");
